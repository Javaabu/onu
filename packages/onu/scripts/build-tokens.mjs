#!/usr/bin/env node
/** Generates src/styles/tokens.css from the DTCG tokens.json at the repo root (R3.12). */
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const tokens = JSON.parse(readFileSync(path.resolve(here, "../../../tokens.json"), "utf8"))
const out = path.resolve(here, "../src/styles/tokens.css")

const fontValue = (v) =>
  v.map((f) => (/[\s\d]/.test(f) && !f.includes("-") ? `"${f}"` : /\s/.test(f) ? `"${f}"` : f)).join(", ")
const vars = (group, prefix) =>
  Object.entries(group).map(
    ([name, t]) => `  --onu-${prefix}${name}: ${Array.isArray(t.$value) ? fontValue(t.$value) : t.$value};`,
  )

const lines = [
  "/* Generated by scripts/build-tokens.mjs from tokens.json. Do not edit by hand. */",
  "",
  ":root {",
  `  --onu-primary: ${tokens.brand.primary.$value};`,
  ...vars(tokens.color.light, ""),
  `  --onu-radius: ${tokens.radius.base.$value};`,
  ...vars(tokens.font, "font-"),
  ...vars(tokens.size, ""),
  ...Object.entries(tokens.density).map(([k, t]) => `  --onu-density-${k}: ${t.$value};`),
  "}",
  "",
  ":root.dark,",
  ':root[data-theme="dark"],',
  ".dark,",
  '[data-theme="dark"] {',
  ...vars(tokens.color.dark, ""),
  "}",
  "",
]
writeFileSync(out, lines.join("\n"))
console.log(`Wrote ${path.relative(process.cwd(), out)}`)
