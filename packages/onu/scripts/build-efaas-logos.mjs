#!/usr/bin/env node
/**
 * Turns eFaas's official logo SVGs (scripts/efaas-logos/efaas-01.svg … -22.svg,
 * from the eFaas brand kit, unchanged) into data modules for the EfaasLogo
 * component: the icon marks (bundled) and the wordmark logos (a separate chunk
 * loaded when one is shown, about 40 kB compressed). The SVGs style their shapes with <style> classes
 * (.cls-1 …), which would clash between logos on the same page, so each shape's
 * class is resolved to plain fill / fill-rule attributes. Shapes, paths and
 * colours are kept exactly.
 *
 *   node scripts/build-efaas-logos.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const dir = path.join(root, "scripts/efaas-logos")
const outIcons = path.join(root, "src/components/form/efaas-logo-icons.data.ts")
const outFull = path.join(root, "src/components/form/efaas-logo-wordmarks.data.ts")
/** The icon-only marks (variants 9, 10, 11, 14, 15): small, bundled with EfaasButton. */
const ICONS = [9, 10, 11, 14, 15]

/** `.cls-1, .cls-2 { fill: #fff; }` → { "cls-1": { fill: "#fff" }, … } */
function parseClasses(css) {
  const classes = {}
  for (const [, selectors, body] of css.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
    const decls = Object.fromEntries(
      body
        .split(";")
        .map((d) => d.split(":").map((s) => s.trim()))
        .filter(([k, v]) => k && v),
    )
    for (const sel of selectors.split(",")) {
      const name = sel.trim().replace(/^\./, "")
      classes[name] = { ...classes[name], ...decls }
    }
  }
  return classes
}

const ATTRS = { d: "d", x: "x", y: "y", width: "width", height: "height", rx: "rx", ry: "ry" }

/** Parses the (flat-ish) logo markup into [tag, attrs, children] nodes. */
function parse(svg) {
  const css = /<style>([\s\S]*?)<\/style>/.exec(svg)?.[1] ?? ""
  const classes = parseClasses(css)
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1]
  const body = svg.replace(/<\?xml[^>]*>/, "").replace(/<defs>[\s\S]*?<\/defs>/, "")
  const rootNode = ["svg", {}, []]
  const stack = [rootNode]
  for (const [, closing, tag, attrText, selfClosing] of body.matchAll(/<(\/?)([a-zA-Z]+)([^>]*?)(\/?)>/g)) {
    if (tag === "svg") continue
    if (closing) {
      stack.pop()
      continue
    }
    const raw = Object.fromEntries([...attrText.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]))
    const attrs = {}
    for (const [k, v] of Object.entries(raw)) if (ATTRS[k]) attrs[ATTRS[k]] = v
    for (const cls of (raw.class ?? "").split(/\s+/).filter(Boolean)) {
      const style = classes[cls] ?? {}
      if (style.fill) attrs.fill = style.fill
      if (style["fill-rule"]) attrs.fillRule = style["fill-rule"]
      if (style.opacity) attrs.opacity = style.opacity
    }
    if (tag !== "g" && tag !== "path" && tag !== "rect") throw new Error(`Unexpected <${tag}>`)
    const node = [tag, attrs, []]
    stack.at(-1)[2].push(node)
    if (!selfClosing) stack.push(node)
  }
  // Drop attribute-less groups: lift their children.
  const flatten = (nodes) =>
    nodes.flatMap(([tag, attrs, children]) =>
      tag === "g" && Object.keys(attrs).length === 0 ? flatten(children) : [[tag, attrs, flatten(children)]],
    )
  return { viewBox, nodes: flatten(rootNode[2]) }
}

const files = readdirSync(dir)
  .filter((f) => /^efaas-\d\d\.svg$/.test(f))
  .sort()
const logos = files.map((f) => parse(readFileSync(path.join(dir, f), "utf8")))

const header = [
  "// Generated by scripts/build-efaas-logos.mjs from eFaas's official logo files. Do not edit.",
  "",
  'import type { EfaasLogoData } from "./efaas-logo-types"',
  "",
]
const entries = (keep) => logos.flatMap((l, i) => (keep(i + 1) ? [`  ${i + 1}: ${JSON.stringify(l)},`] : []))

writeFileSync(
  outIcons,
  [
    ...header,
    "/** The aspect ratio (viewBox) of every variant, so a logo that is still loading keeps its size. */",
    `export const EFAAS_LOGO_VIEWBOXES: Record<number, string> = ${JSON.stringify(Object.fromEntries(logos.map((l, i) => [i + 1, l.viewBox])))}`,
    "",
    "/** The icon-only marks. */",
    "export const EFAAS_LOGO_ICONS: Record<number, EfaasLogoData> = {",
    ...entries((n) => ICONS.includes(n)),
    "}",
    "",
  ].join("\n"),
)
writeFileSync(
  outFull,
  [
    ...header,
    "/** The full logos (wordmark, with tagline, stacked), loaded on demand. */",
    "export const EFAAS_LOGO_WORDMARKS: Record<number, EfaasLogoData> = {",
    ...entries((n) => !ICONS.includes(n)),
    "}",
    "",
  ].join("\n"),
)
console.log(`Wrote ${path.relative(root, outIcons)} and ${path.relative(root, outFull)} (${logos.length} logos)`)
