/*
 * Official Bank of Maldives assets (R16.8), supplied by BML and inlined as
 * React components so they need no asset pipeline. The artwork is unchanged:
 * only editor ids, metadata and empty groups were removed. Gradient and clip
 * ids are generated per instance, so several logos can share a page.
 */

export interface BmlLogoProps extends Omit<React.ComponentProps<"svg">, "children"> {
  /** Accessible name. Defaults to the brand name. Ignored when `decorative`. */
  title?: string
  /** Hide from assistive technology, e.g. next to visible text that already names the method. */
  decorative?: boolean
}

/** A per-instance id prefix that is safe inside `url(#…)`. */
function useSvgIds() {
  return `bml${React.useId().replace(/[^a-zA-Z0-9_-]/g, "")}`
}

function a11yProps(name: string, decorative: boolean | undefined, props: BmlLogoProps) {
  if (decorative) return { "aria-hidden": true as const, focusable: "false" as const }
  return { role: "img", "aria-label": props["aria-label"] ?? name }
}

