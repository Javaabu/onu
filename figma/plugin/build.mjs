#!/usr/bin/env node
/**
 * Bundles the "Onu kit" Figma plugin (src/code.ts → code.js). tokens.json and the
 * @javaabu/onu version are inlined, so the built code.js is self-contained and is
 * committed: designers can import manifest.json without building.
 *
 *   pnpm figma:plugin            (or pnpm --filter onu-figma build:plugin)
 */
import { writeFileSync } from "node:fs"
import path from "node:path"
import { pathToFileURL } from "node:url"
import { build } from "rolldown"

const here = import.meta.dirname
export const outFile = path.join(here, "code.js")

/** Returns the bundled plugin source. */
export async function bundle() {
  const result = await build({
    input: path.join(here, "src/code.ts"),
    platform: "browser",
    logLevel: "warn",
    // Figma's plugin sandbox runs modern JavaScript; lowering keeps older desktop apps working.
    transform: { target: "es2017" },
    write: false,
    output: {
      format: "iife",
      banner:
        "// Onu kit Figma plugin. Generated by figma/plugin/build.mjs from figma/plugin/src. Do not edit by hand.",
      minify: false,
    },
  })
  return result.output[0].code
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  writeFileSync(outFile, await bundle())
  console.log("Built figma/plugin/code.js")
}
