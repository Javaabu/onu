#!/usr/bin/env node
/**
 * Writes figma/plugin/src/icons.generated.ts: the Lucide icons the Onu kit draws
 * (as SVG strings), taken from the installed lucide-react so they match the library.
 *
 *   pnpm --filter onu-figma icons
 */
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import path from "node:path"
import { pathToFileURL } from "node:url"

export const ICONS = [
  "arrow-down-right",
  "arrow-up-right",
  "bell",
  "calendar",
  "chart-column",
  "check",
  "chevron-down",
  "chevron-left",
  "chevron-right",
  "chevron-up",
  "chevrons-left",
  "chevrons-right",
  "circle-check",
  "circle-question-mark",
  "circle-x",
  "download",
  "ellipsis",
  "eye",
  "file-text",
  "filter",
  "house",
  "inbox",
  "info",
  "layout-dashboard",
  "log-out",
  "mail",
  "menu",
  "minus",
  "moon",
  "panel-left",
  "pencil",
  "plus",
  "search",
  "settings",
  "sun",
  "trash",
  "triangle-alert",
  "upload",
  "user",
  "users",
  "x",
]

const here = import.meta.dirname
const require = createRequire(import.meta.url)
const pkgDir = path.dirname(require.resolve("lucide-react/package.json"))
const version = JSON.parse(readFileSync(path.join(pkgDir, "package.json"), "utf8")).version

const attrs = (props) =>
  Object.entries(props)
    .filter(([k]) => k !== "key")
    .map(([k, v]) => `${k}='${v}'`)
    .join(" ")

const entries = []
for (const name of ICONS) {
  let file = path.join(pkgDir, "dist/esm/icons", `${name}.mjs`)
  // Aliases (e.g. trash-2 → trash) only re-export the canonical icon module.
  const alias = /export \{ default \} from '\.\/([\w-]+\.mjs)'/.exec(readFileSync(file, "utf8"))
  if (alias) file = path.join(path.dirname(file), alias[1])
  const mod = await import(pathToFileURL(file).href)
  const body = mod.__iconData.node.map(([tag, props]) => `<${tag} ${attrs(props)}/>`).join("")
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' width='24' height='24' fill='none' stroke='black' stroke-width='2' stroke-linecap='round' stroke-linejoin='round'>${body}</svg>`
  entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`)
}

const out = path.join(here, "../src/icons.generated.ts")
const source = `// Generated by figma/plugin/scripts/icons.mjs from lucide-react ${version} (ISC). Do not edit by hand.
export const LUCIDE: Record<string, string> = {
${entries.join("\n")}
}
`
// Format with the repo's Prettier config so `pnpm format:check` stays green.
const prettierPath = createRequire(path.join(here, "../../../package.json")).resolve("prettier")
const prettierModule = await import(pathToFileURL(prettierPath).href)
const prettier = prettierModule.default ?? prettierModule
const options = (await prettier.resolveConfig(out)) ?? {}
writeFileSync(out, await prettier.format(source, { ...options, plugins: [], filepath: out }))
console.log(`Wrote ${entries.length} icons.`)
